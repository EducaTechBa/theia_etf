#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

// Define images to encode
const images = [
    {
        filePath: '../src/browser/images/coming_soon.jpg',
        exportName: 'comingSoonImage',
        mimeType: 'image/jpeg'
    },
    {
        filePath: '../src/browser/images/friendly_asistent.png',
        exportName: 'friendlyAssistantImage',
        mimeType: 'image/png'
    },
    {
        filePath: '../src/browser/images/tired_asistent.png',
        exportName: 'tiredAssistantImage',
        mimeType: 'image/png'
    }
];

// Encode each image
const encodedImages = images.map(img => {
    const imagePath = path.join(__dirname, img.filePath);
    const imageBuffer = fs.readFileSync(imagePath);
    const base64Image = imageBuffer.toString('base64');
    return `export const ${img.exportName} = 'data:${img.mimeType};base64,${base64Image}';`;
});

// Create the TypeScript module content
const moduleContent = `// This file is auto-generated by scripts/encode-images.js
// Do not edit manually

${encodedImages.join('\n\n')}
`;

// Write to src directory so TypeScript can compile it
const outputDir = path.join(__dirname, '../src/browser');
const outputPath = path.join(outputDir, 'encoded-images.ts');

// Ensure output directory exists
if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
}

fs.writeFileSync(outputPath, moduleContent, 'utf8');

console.log(`Successfully encoded ${images.length} images to src/browser/encoded-images.ts`);
